// Converts eBible.org "VPL" (verse per line) texts into public/bible/<version>/<BOOK>.json
// and src/data/bibleChapters.ts (chapter count per book per version).
//
// Usage: node scripts/build-bible.mjs <version-id>=<path/to/xxx_vpl.txt> [...]
// Sources: https://ebible.org/Scriptures/<translationId>_vpl.zip (ayt=indayt, webc=eng-web-c, bsb=engbsb).
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Greek Esther / Daniel share the Hebrew book ids so a reading position survives a version switch.
const BOOK_ALIASES = { ESG: 'EST', DNG: 'DAN' };
const LINE = /^([1-3A-Z]{3}) (\d+):(\d+) (.*)$/;

const counts = {};
for (const arg of process.argv.slice(2)) {
  const [versionId, file] = arg.split('=');
  const books = {};
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = LINE.exec(line);
    if (!match) continue;
    const [, rawBook, chapter, verse, text] = match;
    const bookId = BOOK_ALIASES[rawBook] ?? rawBook;
    const chapters = (books[bookId] ??= {});
    (chapters[chapter] ??= []).push([Number(verse), text.replace(/\s+/g, ' ').trim()]);
  }
  const outDir = join(root, 'public', 'bible', versionId);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  counts[versionId] = {};
  for (const [bookId, chapters] of Object.entries(books)) {
    writeFileSync(join(outDir, `${bookId}.json`), JSON.stringify(chapters));
    counts[versionId][bookId] = Math.max(...Object.keys(chapters).map(Number));
  }
  console.log(`${versionId}: ${Object.keys(books).length} books`);
}

const body = Object.entries(counts)
  .map(([versionId, books]) => {
    const entries = Object.entries(books).map(([id, count]) => `${/^\d/.test(id) ? `'${id}'` : id}: ${count}`);
    return `  ${versionId}: { ${entries.join(', ')} },`;
  })
  .join('\n');
writeFileSync(
  join(root, 'src', 'data', 'bibleChapters.ts'),
  `// Generated by scripts/build-bible.mjs — do not edit by hand.\n/** Number of chapters per book id, per Bible version. A missing book is not in that version. */\nexport const BIBLE_CHAPTERS: Record<string, Record<string, number>> = {\n${body}\n};\n`,
);
