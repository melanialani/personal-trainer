"""Builds src/data/growthStandards.ts from the official WHO growth tables.

Sources (downloaded as-is from cdn.who.int):
- WHO Child Growth Standards 2006 (0-5 years), z-score expanded tables (by day):
  weight-for-age, length/height-for-age, BMI-for-age; head circumference (by month).
- WHO Growth Reference 2007 (5-19 years), z-score tables (by month):
  height-for-age and BMI-for-age (61-228 months), weight-for-age (61-120 months).

Only the LMS parameters (L = skewness, M = median, S = coefficient of variation) are kept, one row per month;
the app derives any z-score / SD line from them (src/lib/growth.ts).

Usage: python3 scripts/build-growth.py   (needs `openpyxl`; downloads the tables into a temp folder)
"""

import os
import sys
import tempfile
import urllib.request

import openpyxl

CDN = 'https://cdn.who.int/media/docs/default-source/child-growth'
S06 = f'{CDN}/child-growth-standards/indicators'
R07 = f'{CDN}/growth-reference-5-19-years'

SEXES = {'male': 'boys', 'female': 'girls'}

# The WHO page stores the 5-10 years weight table under an "hfa-" file name; its content is weight-for-age.
WFA_5_10 = {
    'boys': f'{R07}/weight-for-age-(5-10-years)/hfa-boys-z-who-2007-exp_0ff9c43c-8cc0-4c23-9fc6-81290675e08b.xlsx',
    'girls': f'{R07}/weight-for-age-(5-10-years)/hfa-girls-z-who-2007-exp_7ea58763-36a2-436d-bef0-7fcfbadd2820.xlsx',
}

# indicator -> URLs ({sex} = boys / girls, or a dict per sex). 'Day' tables are sampled once per month.
TABLES = {
    'weight': [f'{S06}/weight-for-age/expanded-tables/wfa-{{sex}}-zscore-expanded-tables.xlsx', WFA_5_10],
    'height': [
        f'{S06}/length-height-for-age/expandable-tables/lhfa-{{sex}}-zscore-expanded-tables.xlsx',
        f'{R07}/height-for-age-(5-19-years)/hfa-{{sex}}-z-who-2007-exp.xlsx',
    ],
    'head': [f'{S06}/head-circumference-for-age/hcfa-{{sex}}-0-5-zscores.xlsx'],
    'bmi': [
        f'{S06}/body-mass-index-for-age/expanded-tables/bfa-{{sex}}-zscore-expanded-tables.xlsx',
        f'{R07}/bmi-for-age-(5-19-years)/bmi-{{sex}}-z-who-2007-exp.xlsx',
    ],
}

DAYS_PER_MONTH = 30.4375
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'data', 'growthStandards.ts')


def read_rows(url, folder):
    path = os.path.join(folder, url.rsplit('/', 1)[-1])
    if not os.path.exists(path):
        request = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (build-growth script)'})
        with urllib.request.urlopen(request, timeout=60) as response, open(path, 'wb') as handle:
            handle.write(response.read())
    sheet = openpyxl.load_workbook(path, read_only=True).active
    rows = list(sheet.iter_rows(values_only=True))
    header = [str(cell) for cell in rows[0]]
    index = {name: header.index(name) for name in ('L', 'M', 'S')}
    key = header[0]  # 'Day' or 'Month'
    return key, [(row[0], row[index['L']], row[index['M']], row[index['S']]) for row in rows[1:] if row[0] is not None]


def monthly(key, rows):
    if key == 'Month':
        return [(int(r[0]), r[1], r[2], r[3]) for r in rows]
    by_day = {int(r[0]): r for r in rows}
    last_month = int(max(by_day) // DAYS_PER_MONTH)
    out = []
    for month in range(0, min(last_month, 60) + 1):
        day = round(month * DAYS_PER_MONTH)
        _, l, m, s = by_day[day]
        out.append((month, l, m, s))
    return out


def fmt(value):
    return f'{value:.5f}'.rstrip('0').rstrip('.')


def main():
    folder = tempfile.mkdtemp(prefix='who-growth-')
    data = {}
    for indicator, sources in TABLES.items():
        data[indicator] = {}
        for sex_key, sex in SEXES.items():
            merged = {}
            for source in sources:
                url = source[sex] if isinstance(source, dict) else source.format(sex=sex)
                key, rows = read_rows(url, folder)
                for row in monthly(key, rows):
                    merged.setdefault(row[0], row)  # 2006 standards win at 60 months
            data[indicator][sex_key] = [merged[m] for m in sorted(merged)]

    lines = [
        '// Generated by scripts/build-growth.py from the official WHO tables - do not edit by hand.',
        '// 0-60 months: WHO Child Growth Standards (2006). 61-228 months: WHO Growth Reference (2007).',
        '// Weight-for-age stops at 120 months (WHO has no weight-for-age reference after 10 years; use BMI-for-age).',
        "import type { Sex } from '../types';",
        '',
        "export type GrowthIndicator = 'weight' | 'height' | 'head' | 'bmi';",
        '/** [age in completed months, L, M, S] */',
        'export type LmsRow = readonly [number, number, number, number];',
        '',
        'export const GROWTH_LMS: Record<GrowthIndicator, Record<Sex, readonly LmsRow[]>> = {',
    ]
    for indicator, by_sex in data.items():
        lines.append(f'  {indicator}: {{')
        for sex_key, rows in by_sex.items():
            body = ','.join(f'[{m},{fmt(l)},{fmt(mm)},{fmt(s)}]' for m, l, mm, s in rows)
            lines.append(f'    {sex_key}: [{body}],')
        lines.append('  },')
    lines.append('};')
    lines.append('')
    with open(OUT, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines))
    counts = {k: {s: len(v) for s, v in by.items()} for k, by in data.items()}
    print('wrote', os.path.normpath(OUT), counts, file=sys.stderr)


if __name__ == '__main__':
    main()
